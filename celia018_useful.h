bool CheckEntityCollision(Entity* pacman, Entity* ghost) {
    int aLeft   = pacman->position.x + PACMAN_COLLISION_X_OFFSET;
    int aRight  = aLeft + PACMAN_COLLISION_WIDTH - 1;
    int aTop    = pacman->position.y + PACMAN_COLLISION_Y_OFFSET;
    int aBottom = aTop + PACMAN_COLLISION_HEIGHT - 1;

    int bLeft   = ghost->position.x + GHOST_COLLISION_X_OFFSET;
    int bRight  = bLeft + GHOST_COLLISION_WIDTH - 1;
    int bTop    = ghost->position.y + GHOST_COLLISION_Y_OFFSET;
    int bBottom = bTop + GHOST_COLLISION_HEIGHT - 1;

    return !(aRight < bLeft || aLeft > bRight || aBottom < bTop || aTop > bBottom);
}

