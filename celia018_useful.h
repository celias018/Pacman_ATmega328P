void DrawMaze(void){
    uint8_t x;
    uint8_t y;

    for(y = 0; y < 20; y++){
        for(x = 0; x < 16; x++){
            uint8_t px = x * TILE_SIZE;
            uint8_t py = y * TILE_SIZE;
            if(maze[y][x] == WALL){
                
                TFT_DrawRectangle(px + 3, py + 3, WALL_THICKNESS, WALL_THICKNESS, ST7735_BLUE); //center

                if(x > 0 && maze[y][x - 1] == WALL){ //connect left
                    TFT_DrawRectangle(px, py + 3, 4, WALL_THICKNESS, ST7735_BLUE);
                }

                if(x < 15 && maze[y][x + 1] == WALL){ //connect right
                    TFT_DrawRectangle(px + 4, py + 3, 4, WALL_THICKNESS, ST7735_BLUE);
                }

                if(y > 0 && maze[y - 1][x] == WALL){ //connect up
                    TFT_DrawRectangle(px + 3, py, WALL_THICKNESS, 4, ST7735_BLUE);
                }

                if(y < 19 && maze[y + 1][x] == WALL){ //connect down
                    TFT_DrawRectangle(px + 3, py + 4, WALL_THICKNESS, 4, ST7735_BLUE);
                }
            }
            else if(maze[y][x] == GHOSTWALL){
                TFT_DrawRectangle(px - 1, py + 3, 13, WALL_THICKNESS, ST7735_RED);
            }
            else if(maze[y][x] == DOT){
                TFT_DrawRectangle(px + 3, py + 3, 2, 2, ST7735_LIGHT_YELLOW);
            }
            else if(maze[y][x] == BIGDOT){
                TFT_DrawRectangle(px + 2, py + 2, 4, 4, ST7735_LIGHT_YELLOW);
            }
        }
    }   
}

bool IsWallPixel(uint8_t x, uint8_t y){ //for wall collisions
    uint8_t tileX = x / TILE_SIZE;
    uint8_t tileY = y / TILE_SIZE;

    if(tileX >= 16 || tileY >= 20){
        return true;
    }
    return maze[tileY][tileX] == WALL;
}
bool IsGhostWallPixel(Entity* ghost, uint8_t x, uint8_t y){
    uint8_t tileX = x / TILE_SIZE;
    uint8_t tileY = y / TILE_SIZE;

    if(tileX >= 16 || tileY >= 20) return true;

    if(ghost->lives == 0){ 
        return maze[tileY][tileX] == WALL; // eaten ghost can enter
    }

    return maze[tileY][tileX] == WALL || maze[tileY][tileX] == GHOSTWALL;
}

bool CanMoveRight(Entity entity){
    uint8_t rightX = entity.position.x + PACMAN_COLLISION_X_OFFSET + PACMAN_COLLISION_WIDTH + entity.speed - 1;
    uint8_t topY = entity.position.y + PACMAN_COLLISION_Y_OFFSET;
    uint8_t middleY = topY + (PACMAN_COLLISION_HEIGHT / 2);
    uint8_t bottomY = topY + PACMAN_COLLISION_HEIGHT - 1;

    return !IsWallPixel(rightX, topY) && !IsWallPixel(rightX, middleY) && !IsWallPixel(rightX, bottomY);
}
bool CanMoveLeft(Entity entity){
    uint8_t leftX = entity.position.x + PACMAN_COLLISION_X_OFFSET - entity.speed;
    uint8_t topY = entity.position.y + PACMAN_COLLISION_Y_OFFSET;
    uint8_t middleY = topY + (PACMAN_COLLISION_HEIGHT / 2);
    uint8_t bottomY = topY + PACMAN_COLLISION_HEIGHT - 1;

    return !IsWallPixel(leftX, topY) && !IsWallPixel(leftX, middleY) && !IsWallPixel(leftX, bottomY);
}
bool CanMoveUp(Entity entity){
    uint8_t topY = entity.position.y + PACMAN_COLLISION_Y_OFFSET - entity.speed;
    uint8_t leftX = entity.position.x + PACMAN_COLLISION_X_OFFSET;
    uint8_t middleX = leftX + (PACMAN_COLLISION_WIDTH / 2);
    uint8_t rightX = leftX + PACMAN_COLLISION_WIDTH - 1;

    return !IsWallPixel(leftX, topY) && !IsWallPixel(middleX, topY) && !IsWallPixel(rightX, topY);
}
bool CanMoveDown(Entity entity){
    uint8_t bottomY = entity.position.y + PACMAN_COLLISION_Y_OFFSET + PACMAN_COLLISION_HEIGHT + entity.speed - 1;
    uint8_t leftX = entity.position.x + PACMAN_COLLISION_X_OFFSET;
    uint8_t middleX = leftX + (PACMAN_COLLISION_WIDTH / 2);
    uint8_t rightX = leftX + PACMAN_COLLISION_WIDTH - 1;

    return !IsWallPixel(leftX, bottomY) && !IsWallPixel(middleX, bottomY) && !IsWallPixel(rightX, bottomY);
}
#pragma region pathfinding
uint8_t GetGhostDir(Entity* ghost){
    if(ghost->xDir == 1) return DIR_LEFT;
    if(ghost->xDir == 2) return DIR_RIGHT;
    if(ghost->yDir == 1) return DIR_UP;
    if(ghost->yDir == 2) return DIR_DOWN;

    return DIR_NONE;
}
bool GhostCanUseTile(Entity* ghost, uint8_t tileX, uint8_t tileY){
    if(tileX >= 16 || tileY >= 20){
        return false;
    }
    if(maze[tileY][tileX] == WALL){
        return false;
    }
    // Alive ghosts cannot cross ghost door
    if(ghost->lives != 0 && maze[tileY][tileX] == GHOSTWALL){
        return false;
    }

    return true;
}
uint8_t OppositeDir(uint8_t dir){
    if(dir == DIR_LEFT)  return DIR_RIGHT;
    if(dir == DIR_RIGHT) return DIR_LEFT;
    if(dir == DIR_UP)    return DIR_DOWN;
    if(dir == DIR_DOWN)  return DIR_UP;

    return DIR_NONE;
}
bool CanGhostMoveDir(Entity* ghost, uint8_t dir){
    int nextX = ghost->position.x;
    int nextY = ghost->position.y;

    if(dir == DIR_LEFT) nextX -= ghost->speed;
    if(dir == DIR_RIGHT) nextX += ghost->speed;
    if(dir == DIR_UP) nextY -= ghost->speed;
    if(dir == DIR_DOWN) nextY += ghost->speed;

    int left = nextX + GHOST_COLLISION_X_OFFSET;
    int right = left + GHOST_COLLISION_WIDTH - 1;
    int top = nextY + GHOST_COLLISION_Y_OFFSET;
    int bottom = top + GHOST_COLLISION_HEIGHT - 1;

    return !IsGhostWallPixel(ghost, left, top) && !IsGhostWallPixel(ghost, right, top) && !IsGhostWallPixel(ghost, left, bottom) && !IsGhostWallPixel(ghost, right, bottom);
}
void AlignGhostPerpendicular(Entity* ghost){
    int16_t centerX = ghost->position.x + ghost->sprite->width / 2;
    int16_t centerY = ghost->position.y + ghost->sprite->length / 2;
    //moving vertical, fix X
    if(ghost->yDir != 0){
        uint8_t tileX = centerX / TILE_SIZE;
        int16_t snappedCenterX = tileX * TILE_SIZE + TILE_SIZE / 2;
        ghost->position.x = snappedCenterX - ghost->sprite->width / 2;
    }
    //moving horizontal, fix Y
    if(ghost->xDir != 0){
        uint8_t tileY = centerY / TILE_SIZE;
        int16_t snappedCenterY = tileY * TILE_SIZE + TILE_SIZE / 2;
        ghost->position.y = snappedCenterY - ghost->sprite->length / 2;
    }
}
uint8_t ChooseGhostDirectionBFS_Search(Entity* ghost, Entity* target, bool allowReverse){
    uint8_t startX = (ghost->position.x + ghost->sprite->width / 2) / TILE_SIZE;
    uint8_t startY = (ghost->position.y + ghost->sprite->length / 2) / TILE_SIZE;
    uint8_t targetX;
    uint8_t targetY;

    if(target->sprite != 0){
        targetX = (target->position.x + target->sprite->width / 2) / TILE_SIZE;
        targetY = (target->position.y + target->sprite->length / 2) / TILE_SIZE;
    }
    else{
        targetX = target->position.x / TILE_SIZE;
        targetY = target->position.y / TILE_SIZE;
    }
    static uint8_t firstDir[20][16];
    static uint16_t queue[320];

    for(uint8_t y = 0; y < 20; y++){
        for(uint8_t x = 0; x < 16; x++){
            firstDir[y][x] = DIR_NONE;
        }
    }
    uint8_t currentDir = GetGhostDir(ghost);
    uint8_t reverseDir = OppositeDir(currentDir);
    uint16_t head = 0;
    uint16_t tail = 0;

    queue[tail++] = startY * 16 + startX;
    firstDir[startY][startX] = 255;
    while(head < tail){
        uint16_t current = queue[head++];
        uint8_t cx = current % 16;
        uint8_t cy = current / 16;
        if(cx == targetX && cy == targetY){
            uint8_t answer = firstDir[cy][cx];
            if(answer == 255){
                return currentDir;
            }
            return answer;
        }
        uint8_t dirs[4] = {DIR_UP, DIR_LEFT, DIR_DOWN, DIR_RIGHT};

        for(uint8_t i = 0; i < 4; i++){
            uint8_t dir = dirs[i];
            if(cx == startX && cy == startY){
                if(!allowReverse && dir == reverseDir){
                    continue;
                }
            }
            int8_t nx = cx;
            int8_t ny = cy;

            if(dir == DIR_LEFT)  nx--;
            if(dir == DIR_RIGHT) nx++;
            if(dir == DIR_UP)    ny--;
            if(dir == DIR_DOWN)  ny++;
            if(nx < 0 || nx >= 16 || ny < 0 || ny >= 20){
                continue;
            }
            if(firstDir[ny][nx] != DIR_NONE){
                continue;
            }
            if(!GhostCanUseTile(ghost, nx, ny)){
                continue;
            }
            if(cx == startX && cy == startY){
                firstDir[ny][nx] = dir;
            }
            else{
                firstDir[ny][nx] = firstDir[cy][cx];
            }
            queue[tail++] = ny * 16 + nx;
        }
    }
    return DIR_NONE;
}
uint8_t ChooseGhostDirectionBFS(Entity* ghost, Entity* target){
    uint8_t dir;
    //try pathfinding without reversing
    dir = ChooseGhostDirectionBFS_Search(ghost, target, false);
    if(dir != DIR_NONE){
        return dir;
    }
    //reverse if no other path
    dir = ChooseGhostDirectionBFS_Search(ghost, target, true);
    if(dir != DIR_NONE){
        return dir;
    }
    return GetGhostDir(ghost);
}
bool GhostAtTileCenter(Entity* ghost){
    uint8_t centerX = ghost->position.x + ghost->sprite->width / 2;
    uint8_t centerY = ghost->position.y + ghost->sprite->length / 2;

    return (centerX % TILE_SIZE == TILE_SIZE / 2) && (centerY % TILE_SIZE == TILE_SIZE / 2);
}
void MoveGhost(Entity* ghost, Entity* target){
    uint8_t dir = GetGhostDir(ghost);
    AlignGhostPerpendicular(ghost);
    if(GhostAtTileCenter(ghost) || !CanGhostMoveDir(ghost, dir)){
        dir = ChooseGhostDirectionBFS(ghost, target);
        ghost->xDir = 0;
        ghost->yDir = 0;
        if(dir == DIR_LEFT)  ghost->xDir = 1;
        if(dir == DIR_RIGHT) ghost->xDir = 2;
        if(dir == DIR_UP)    ghost->yDir = 1;
        if(dir == DIR_DOWN)  ghost->yDir = 2;
    }
    dir = GetGhostDir(ghost);
    if(CanGhostMoveDir(ghost, dir)){
        if(dir == DIR_LEFT)       ghost->position.x -= ghost->speed;
        else if(dir == DIR_RIGHT) ghost->position.x += ghost->speed;
        else if(dir == DIR_UP)    ghost->position.y -= ghost->speed;
        else if(dir == DIR_DOWN)  ghost->position.y += ghost->speed;
    }
}
//for return to home
bool GhostReachedTile(Entity* ghost, uint8_t tileX, uint8_t tileY){
    int16_t targetX = tileX * TILE_SIZE + TILE_SIZE / 2;
    int16_t targetY = tileY * TILE_SIZE + TILE_SIZE / 2;
    int16_t ghostCenterX = ghost->position.x + ghost->sprite->width / 2;
    int16_t ghostCenterY = ghost->position.y + ghost->sprite->length / 2;
    int16_t dx = ghostCenterX - targetX;
    int16_t dy = ghostCenterY - targetY;

    if(dx < 0) dx = -dx;
    if(dy < 0) dy = -dy;

    return dx <= ghost->speed && dy <= ghost->speed;
}
