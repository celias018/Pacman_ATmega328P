void Buzzer_Play(unsigned int freq){
    if(freq == 0){
        OCR1A = 0;
        return;
    }

    ICR1 = (16000000UL / (8UL * freq)) - 1;
    OCR1A = ICR1 / 2;   // 50% duty cycle
}
void Buzzer_Stop(){
    OCR1A = 0;
}
